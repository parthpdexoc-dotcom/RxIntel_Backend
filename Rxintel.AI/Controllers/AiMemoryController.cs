using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Extensions.Logging;
using Rxintel.Generic.Api;
using Rxintel.Generic.Common.Implementations.Responses;
using Rxintel.Generic.Services.Interfaces;
using Rxintel.Generic.Services.MetaAI;

namespace Rxintel.AI.Controllers
{
    [ApiController]
    [Route("api/ai/memory")]
    [Route("ai/memory")]
    [Route("api/erx-audit/ai-suggestion")]
    [Route("erx-audit/ai-suggestion")]
    public class AiMemoryController : BaseController
    {
        private readonly IMetaAiClient _metaAiClient;
        private readonly IAutonomousAuditLearningService _learningService;
        private readonly ILogger<AiMemoryController> _logger;

        public AiMemoryController(
            IMetaAiClient metaAiClient,
            IAutonomousAuditLearningService learningService,
            ILogger<AiMemoryController> logger)
        {
            _metaAiClient = metaAiClient;
            _learningService = learningService;
            _logger = logger;
        }

        /// <summary>
        /// Retrieves or generates an authoritative HIPAA / DEA / CMS fix suggestion using Muse AI
        /// for a prescription discrepancy to help the pharmacy owner resolve issues compliantly.
        /// </summary>
        [HttpPost("suggestion")]
        public async Task<ActionResult<SuccessResult<MuseDiscrepancySuggestionResult>>> GetSuggestion(
            [FromBody] MuseDiscrepancySuggestionRequest request,
            System.Threading.CancellationToken cancellationToken)
        {
            if (request == null || string.IsNullOrWhiteSpace(request.FieldName))
            {
                return BadRequest(SuccessResult<MuseDiscrepancySuggestionResult>.BadRequest("FieldName is required for discrepancy suggestion."));
            }

            _logger.LogInformation(
                "[AiMemoryController:Suggestion] Requesting HIPAA suggestion from Muse AI for field: '{FieldName}', Rx: '{RxNumber}'",
                request.FieldName, request.RxNumber);

            var result = await _metaAiClient.GetDiscrepancySuggestionAsync(request, cancellationToken);
            return Ok(SuccessResult<MuseDiscrepancySuggestionResult>.Ok(result, "HIPAA discrepancy suggestion generated by Muse AI."));
        }

        /// <summary>
        /// Executes an autonomous clinical learning sweep across all or specific batch records,
        /// training Muse's memory bank and auto-resolving false discrepancies with ZERO human interaction.
        /// </summary>
        [HttpPost("auto-learn")]
        public async Task<ActionResult<SuccessResult<AutonomousLearningReportDto>>> RunAutonomousLearning(
            [FromQuery] Guid? batchId = null)
        {
            _logger.LogInformation("[AiMemoryController:AutoLearn] Triggering autonomous learning sweep for BatchId: {BatchId}...", batchId);
            var report = await _learningService.RunAutonomousLearningAsync(batchId);
            return Ok(SuccessResult<AutonomousLearningReportDto>.Ok(report,
                $"Autonomous learning complete. {report.AutonomouslyResolvedCount} discrepancies auto-resolved, {report.NewMemoriesLearned} new memories learned with zero human clicks."));
        }

        /// <summary>
        /// Retrieves statistical metrics of Muse AI's active continuous clinical memory.
        /// </summary>
        [HttpGet("summary")]
        public ActionResult<SuccessResult<MuseMemorySummaryDto>> GetMemorySummary()
        {
            var summary = _metaAiClient.GetMemorySummary();
            return Ok(SuccessResult<MuseMemorySummaryDto>.Ok(summary, "Muse AI memory summary retrieved."));
        }

        /// <summary>
        /// Retrieves all remembered clinical equivalences and rules, with optional category filtering and search.
        /// </summary>
        [HttpGet("entries")]
        public ActionResult<SuccessResult<List<MuseMemoryEntry>>> GetMemoryEntries(
            [FromQuery] string? category = null,
            [FromQuery] string? search = null)
        {
            var entries = _metaAiClient.GetAllMemories(category, search);
            return Ok(SuccessResult<List<MuseMemoryEntry>>.Ok(entries, $"Retrieved {entries.Count} memory entries."));
        }

        /// <summary>
        /// Updates or teaches Muse a new clinical rule, equivalence, or discrepancy resolution override.
        /// </summary>
        [HttpPost("update")]
        public ActionResult<SuccessResult<MuseMemoryEntry>> UpdateMemory([FromBody] MuseMemoryEntry request)
        {
            if (request == null || string.IsNullOrWhiteSpace(request.MmValue) || string.IsNullOrWhiteSpace(request.ErxValue))
            {
                return BadRequest(SuccessResult<MuseMemoryEntry>.BadRequest("Both MM value and ERX value are required to update Muse memory."));
            }

            _logger.LogInformation(
                "[AiMemoryController:Update] Training Muse Memory: Category='{Category}', MM='{MmVal}', ERX='{ErxVal}', Reason='{Reason}'",
                request.Category, request.MmValue, request.ErxValue, request.Reason);

            request.Source = string.IsNullOrWhiteSpace(request.Source) ? "Auditor / User API" : request.Source;
            var saved = _metaAiClient.UpdateMemory(request);

            return Ok(SuccessResult<MuseMemoryEntry>.Ok(saved, "Muse AI successfully updated memory. This equivalence is permanently remembered."));
        }

        /// <summary>
        /// Deletes a specific remembered entry from Muse's memory store.
        /// </summary>
        [HttpDelete("{key}")]
        public ActionResult<SuccessResult<string>> DeleteMemory(string key)
        {
            var success = _metaAiClient.DeleteMemory(key);
            if (!success)
            {
                return NotFound(SuccessResult<string>.NotFound($"Memory key '{key}' not found."));
            }

            _logger.LogInformation("[AiMemoryController:Delete] Deleted memory key '{Key}' from Muse memory.", key);
            return Ok(SuccessResult<string>.Ok(key, $"Memory key '{key}' deleted successfully."));
        }

        /// <summary>
        /// Verifies whether Muse's memory recognizes an equivalence, or runs a live inference test against Meta AI.
        /// </summary>
        [HttpPost("test-evaluation")]
        public async Task<ActionResult<SuccessResult<MetaAiEvaluationResult>>> TestEvaluation(
            [FromBody] TestMemoryEvaluationRequest request)
        {
            if (request == null || string.IsNullOrWhiteSpace(request.MmValue) || string.IsNullOrWhiteSpace(request.ErxValue))
            {
                return BadRequest(SuccessResult<MetaAiEvaluationResult>.BadRequest("Both MM and ERX values are required."));
            }

            var category = request.Category?.Trim().ToUpperInvariant() ?? "SIG";

            if (category == "SIG")
            {
                var result = await _metaAiClient.EvaluateSigAsync(request.MmValue, request.ErxValue);
                return Ok(SuccessResult<MetaAiEvaluationResult>.Ok(result, "SIG evaluated via Muse AI."));
            }

            if (category == "QUANTITY")
            {
                if (decimal.TryParse(request.MmValue, out var mmQ) && decimal.TryParse(request.ErxValue, out var erxQ))
                {
                    var result = await _metaAiClient.EvaluateQuantityDispensedAsync(mmQ, erxQ, request.Context, request.Context, null);
                    return Ok(SuccessResult<MetaAiEvaluationResult>.Ok(result, "Quantity evaluated via Muse AI."));
                }
            }

            if (category == "DAYS_SUPPLY")
            {
                if (int.TryParse(request.MmValue, out var mmD) && int.TryParse(request.ErxValue, out var erxD))
                {
                    var result = await _metaAiClient.EvaluateDaysSupplyAsync(mmD, erxD, request.Context, request.Context, null);
                    return Ok(SuccessResult<MetaAiEvaluationResult>.Ok(result, "Days Supply evaluated via Muse AI."));
                }
            }

            // Fallback direct check against MuseClinicalMemoryStore
            var matched = MuseClinicalMemoryStore.TryGetResolution(category, request.MmValue, request.ErxValue, request.Context, out var entry);
            var evalResult = new MetaAiEvaluationResult
            {
                IsCompliant = matched && (entry?.IsCompliant ?? false),
                Confidence = entry?.Confidence ?? (matched ? 1.0 : 0.0),
                Model = "muse-memory",
                Evaluator = matched ? $"Muse Learned Memory ({entry?.Source})" : "Muse AI (Unrecognized)",
                Reason = entry?.Reason ?? (matched ? "Recognized by Muse Memory" : "Not yet recognized in Muse Memory"),
                LatencyMs = 0,
                FromCache = matched
            };

            return Ok(SuccessResult<MetaAiEvaluationResult>.Ok(evalResult, "Evaluation complete."));
        }
    }

    public class TestMemoryEvaluationRequest
    {
        public string Category { get; set; } = "SIG";
        public string MmValue { get; set; } = string.Empty;
        public string ErxValue { get; set; } = string.Empty;
        public string? Context { get; set; }
    }
}
